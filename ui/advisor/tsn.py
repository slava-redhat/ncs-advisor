"""Turn a finished advisor conversation into a downloadable TSN bundle.

A TSN is the Ansible scaffold under docs/template/TSN-EXAMPLE (apply / rollback /
validate via tags). Here we copy that scaffold and ask the LLM to fill the
editable files from the diagnosed solution, then tar.gz it for download.

ponytail: LLM fills the task files; anything it omits or a total failure falls
back to the template content so the tarball is always a valid, if skeletal, TSN.
"""
import io
import json
import re
import tarfile
import time
from pathlib import Path

# Bundled under ui/ so it ships in the image (build context is ./ui).
# This file is ui/advisor/tsn.py → parents[1] is ui/.
_TEMPLATE = Path(__file__).resolve().parents[1] / "tsn_template" / "TSN-EXAMPLE"
_CONVENTIONS = _TEMPLATE.parent / "docs" / "creating-a-new-tsn.md"

# Editable files the LLM may rewrite (relative to the TSN dir). playbook.yml is
# templated deterministically below, so it's not in this set.
_EDITABLE = [
    "README.md",
    "vars/main.yml",
    "pre_tasks/detect.yml",
    "roles/install/tasks/main.yml",
    "roles/rollback/tasks/main.yml",
    "roles/validate/tasks/main.yml",
]


def _template_files() -> dict[str, str]:
    """All files under the template dir, keyed by POSIX relative path."""
    out = {}
    for p in sorted(_TEMPLATE.rglob("*")):
        if p.is_file():
            out[p.relative_to(_TEMPLATE).as_posix()] = p.read_text()
    return out


def make_tsn_id(version: str | None, cve_ids: list[str], issue_type: str) -> str:
    """Stable-ish id: prefer a CVE, else issue_type + version."""
    if cve_ids:
        return f"TSN-{cve_ids[0].upper()}"
    slug = re.sub(r"[^A-Za-z0-9]+", "-", (issue_type or "issue")).strip("-").lower()
    ver = re.sub(r"[^0-9.]", "", version or "") or "x"
    return f"TSN-{slug}-{ver}"


def _strip_fence(text: str) -> str:
    """Peel a ```json ... ``` wrapper the model may add."""
    t = text.strip()
    if t.startswith("```"):
        t = re.sub(r"^```[a-zA-Z]*\n?", "", t)
        t = re.sub(r"\n?```$", "", t)
    return t.strip()


def _llm_fill(tsn_id, conversation, solution, templates) -> dict[str, str]:
    """Ask the LLM for filled editable files. Returns {} on any failure."""
    try:
        # lazy imports keep this module importable (and self-checkable) offline
        from langchain_core.messages import HumanMessage, SystemMessage
        from .llm import get_llm
    except Exception:
        return {}
    conventions = _CONVENTIONS.read_text() if _CONVENTIONS.exists() else ""
    ref = "\n\n".join(f"### {name}\n```\n{templates[name]}\n```"
                      for name in _EDITABLE if name in templates)
    sys = SystemMessage(content=(
        "You convert a diagnosed Nokia NCS troubleshooting solution into a TSN "
        "Ansible bundle. A TSN exposes apply / rollback / validate on one playbook "
        "via per-task tags. Follow these conventions exactly:\n\n"
        f"{conventions}\n\n"
        "Here are the template files you must rewrite (keep the structure, tags, "
        "marker discipline, and YAML validity; replace placeholders with real steps "
        "derived ONLY from the solution — invent nothing not implied by it):\n\n"
        f"{ref}\n\n"
        f"The TSN id is {tsn_id}. Return ONLY a JSON object mapping each of these "
        f"relative paths to its full new file content (as a string): {_EDITABLE}. "
        "No prose, no code fence — just the JSON object. If the solution doesn't "
        "support a given file (e.g. no rollback is possible), keep that file close "
        "to the template placeholder rather than fabricating steps."))
    user = HumanMessage(content=(
        f"CONVERSATION:\n{conversation}\n\nFINAL DIAGNOSED SOLUTION:\n{solution}"))
    try:
        raw = get_llm(max_tokens=8192).with_retry(stop_after_attempt=2).invoke([sys, user])
        data = json.loads(_strip_fence(raw.content))
        return {k: v for k, v in data.items() if k in _EDITABLE and isinstance(v, str)}
    except Exception:
        return {}


def _solution_readme(tsn_id, solution, templates) -> str:
    """README that always carries the solution text, even if the LLM punted."""
    return (f"# {tsn_id}\n\n"
            "Generated by NCS Advisor from an approved troubleshooting session.\n"
            "Review every task before running against real hosts — this is a "
            "scaffold grounded in the diagnosis below, not a tested release.\n\n"
            "## Diagnosed solution\n\n"
            f"{solution}\n")


def build_tsn_tarball(conversation: str, solution: str, tsn_id: str) -> bytes:
    """Build a TSN dir from the template + LLM-filled files; return .tar.gz bytes."""
    templates = _template_files()
    files = dict(templates)                       # start from the scaffold
    files.update(_llm_fill(tsn_id, conversation, solution, templates))  # overlay LLM

    # Deterministic bits the LLM shouldn't touch.
    if "playbook.yml" in files:
        files["playbook.yml"] = re.sub(r"(?m)^(\s*- name:) .*$",
                                       rf"\1 {tsn_id}", files["playbook.yml"], count=1)
    # Guarantee the solution is captured even if the LLM left README as placeholder.
    if "README.md" not in files or "placeholder" in files["README.md"].lower() \
            or "Template for a new TSN" in files.get("README.md", ""):
        files["README.md"] = _solution_readme(tsn_id, solution, templates)

    buf = io.BytesIO()
    now = time.time()
    with tarfile.open(fileobj=buf, mode="w:gz") as tar:
        for rel, content in sorted(files.items()):
            data = content.encode()
            info = tarfile.TarInfo(name=f"{tsn_id}/{rel}")
            info.size = len(data)
            info.mtime = now
            info.mode = 0o644
            tar.addfile(info, io.BytesIO(data))
    return buf.getvalue()


def _selfcheck():
    tid = make_tsn_id("25.7", ["cve-2026-1"], "security")
    assert tid == "TSN-CVE-2026-1", tid
    assert make_tsn_id("25.7", [], "Node NotReady") == "TSN-node-notready-25.7"
    tb = build_tsn_tarball("conv", "do the fix", "TSN-TEST")
    with tarfile.open(fileobj=io.BytesIO(tb)) as tar:
        names = tar.getnames()
        assert "TSN-TEST/playbook.yml" in names, names
        assert "TSN-TEST/roles/install/tasks/main.yml" in names, names
        readme = tar.extractfile("TSN-TEST/README.md").read().decode()
    assert "do the fix" in readme, "solution must survive into README"
    print("ok: tsn self-check passed")


if __name__ == "__main__":
    _selfcheck()
